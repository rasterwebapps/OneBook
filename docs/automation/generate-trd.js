#!/usr/bin/env node
/**
 * generate-trd.js
 * Auto-generate docs/business/TRD.md from REQ-*.md files.
 * Extracts Technical Specification sections from each requirement file.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { glob } = require('glob');

const ROOT = path.resolve(__dirname, '../..');
const REQ_DIR = path.join(ROOT, 'docs/requirements/active');
const OUTPUT_FILE = path.join(ROOT, 'docs/business/TRD.md');

/**
 * Parse metadata from a REQ file.
 */
function parseMetadata(content) {
  const meta = { reqId: '', title: '', status: 'UNKNOWN', priority: 'MEDIUM', owner: '', milestone: '' };
  const titleMatch = content.match(/^#\s+REQ-(\d+):\s+(.+)$/m);
  if (titleMatch) {
    meta.reqId = `REQ-${titleMatch[1]}`;
    meta.title = titleMatch[2].trim();
  }
  for (const line of content.split('\n')) {
    const s = line.match(/^\*\*Status:\*\*\s+(\S+)/); if (s) meta.status = s[1];
    const p = line.match(/^\*\*Priority:\*\*\s+(CRITICAL|HIGH|MEDIUM|LOW)/); if (p) meta.priority = p[1];
    const o = line.match(/^\*\*Owner:\*\*\s+(.+)$/); if (o) meta.owner = o[1].trim();
    const m = line.match(/^\*\*Milestone:\*\*\s+(.+)$/); if (m) meta.milestone = m[1].trim();
    const trd = line.match(/^\*\*Linked TRD:\*\*\s+\[(.+?)\]/); if (trd) meta.linkedTrd = trd[1];
  }
  return meta;
}

/**
 * Extract a named section.
 */
function extractSection(content, sectionName) {
  const regex = new RegExp(
    `^##\\s+(?:\\d+\\.\\s+)?${sectionName}\\s*\n([\\s\\S]*?)(?=^##\\s+|^---\\s*$|$)`,
    'mi'
  );
  const match = content.match(regex);
  return match ? match[1].trim() : '';
}

/**
 * Main TRD generation.
 */
async function generateTrd() {
  console.log('🔍 Scanning requirement files for TRD generation...');

  const reqFiles = await glob('REQ-*.md', { cwd: REQ_DIR });
  reqFiles.sort();

  if (reqFiles.length === 0) {
    console.warn('⚠️  No REQ-*.md files found.');
    process.exit(1);
  }

  console.log(`📄 Found ${reqFiles.length} requirement files`);

  const requirements = [];
  for (const file of reqFiles) {
    const content = fs.readFileSync(path.join(REQ_DIR, file), 'utf8');
    const meta = parseMetadata(content);
    const technicalSpec = extractSection(content, 'Technical Specification');
    const implementationSection = extractSection(content, 'Implementation');

    requirements.push({ file, meta, technicalSpec, implementationSection });
    console.log(`  ✓ ${meta.reqId}: ${meta.title}`);
  }

  const now = new Date().toISOString().split('T')[0];

  let trd = `# Technical Requirements Document (TRD)
## OneBook — Nexus Universal Accounting OS

> **Auto-generated from REQ-*.md files. Version: Living Document.**
> Generated: ${now} by \`docs/automation/generate-trd.js\`

---

## Table of Contents

`;

  for (let i = 0; i < requirements.length; i++) {
    const { meta } = requirements[i];
    trd += `${i + 1}. [${meta.reqId}: ${meta.title}](#${meta.reqId.toLowerCase()})\n`;
  }
  trd += `\n---\n\n`;

  // Technical specifications per requirement
  for (const req of requirements) {
    const { meta, technicalSpec, implementationSection } = req;

    trd += `## ${meta.reqId}: ${meta.title}

**Priority:** ${meta.priority} | **Owner:** ${meta.owner} | **Milestone:** ${meta.milestone} | **Linked TRD:** ${meta.linkedTrd || '—'}

`;

    if (technicalSpec) {
      trd += `### Technical Specification\n\n${technicalSpec}\n\n`;
    } else {
      trd += `### Technical Specification\n\n*See [${req.file}](../requirements/active/${req.file}) for full specification.*\n\n`;
    }

    if (implementationSection) {
      trd += `### Implementation Notes\n\n${implementationSection}\n\n`;
    }

    trd += `**Full Requirement:** [${req.file}](../requirements/active/${req.file})\n\n---\n\n`;
  }

  // Implementation files summary
  trd += `## Implementation Files Summary\n\n`;
  trd += `| Req ID | Key Implementation Files |\n`;
  trd += `|--------|-------------------------|\n`;

  for (const req of requirements) {
    const { meta, implementationSection } = req;
    // Extract Java file names from implementation section
    const javaFiles = (implementationSection || '').match(/`[\w]+\.java`/g) || [];
    const sqlFiles = (implementationSection || '').match(/`V\d+__[\w]+\.sql`/g) || [];
    const allFiles = [...new Set([...javaFiles, ...sqlFiles])].slice(0, 4);
    trd += `| ${meta.reqId} | ${allFiles.join(', ') || '—'} |\n`;
  }

  trd += `\n---\n\n*Auto-generated by \`docs/automation/generate-trd.js\` on ${now}. Do not edit manually.*\n`;

  fs.writeFileSync(OUTPUT_FILE, trd, 'utf8');
  console.log(`\n✅ TRD generated: ${OUTPUT_FILE}`);
  console.log(`   Total requirements: ${requirements.length}`);
  console.log(`   Output size: ${(trd.length / 1024).toFixed(1)} KB`);
}

generateTrd().catch((err) => {
  console.error('❌ Failed to generate TRD:', err.message);
  process.exit(1);
});
